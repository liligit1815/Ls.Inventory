-- LS Inventory 0.3.1 → 0.3.2 · PostgreSQL · 在原项目数据库的 pgAdmin 查询工具中整份执行。
-- 先停 IIS 站点和应用池，备份数据库。用有权创建表、索引并授权的账号执行。
BEGIN;
SET LOCAL search_path = lite, pg_temp;       -- 与旧站点 Search Path 一致；若业务表在 public，将 lite 改为 public。
SET LOCAL ls_inventory_upgrade.app_role = ''; -- 网站的 PostgreSQL Username；与当前执行账号相同时留空。

SELECT pg_catalog.pg_advisory_xact_lock(82461002);
DO $check$
DECLARE
    s text := current_schema();
    runtime_role text := nullif(current_setting('ls_inventory_upgrade.app_role'), '');
BEGIN
    IF s IS NULL OR s NOT IN ('lite', 'public') THEN
        RAISE EXCEPTION '找不到指定的业务 schema，请检查 search_path。';
    END IF;
    IF to_regclass(format('%I.products', s)) IS NULL
       OR to_regclass(format('%I.audit_logs', s)) IS NULL
       OR to_regclass(format('%I.movements', s)) IS NULL THEN
        RAISE EXCEPTION '未找到旧版商品、流水和操作日志表。请核对当前数据库与脚本开头的 search_path。';
    END IF;
    IF (SELECT count(*) FROM pg_attribute
        WHERE attrelid = 'products'::regclass AND NOT attisdropped
          AND ((attname IN ('quantity','warning_quantity') AND atttypid = 'integer'::regtype)
               OR (attname = 'id' AND atttypid = 'uuid'::regtype) OR attname = 'category')) <> 4 THEN
        RAISE EXCEPTION '商品表结构与 0.3.1 不符，已停止升级。';
    END IF;
    IF runtime_role IS NOT NULL AND NOT EXISTS (SELECT FROM pg_roles WHERE rolname = runtime_role) THEN
        RAISE EXCEPTION '网站数据库账号 % 不存在。', runtime_role;
    END IF;
END
$check$;

CREATE TABLE IF NOT EXISTS product_histories (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  uuid NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    changed_at  timestamptz NOT NULL,
    user_name   text NOT NULL,
    quantity    integer NOT NULL,
    before_info jsonb,
    after_info  jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_product_histories_product_id_changed_at_id
    ON product_histories (product_id, changed_at, id);

-- 这两个函数只用于当前数据库会话。整数合法时才转换，以免把旧小数库存四舍五入。
CREATE OR REPLACE FUNCTION pg_temp.ls032_quantity(v jsonb) RETURNS integer
LANGUAGE plpgsql IMMUTABLE STRICT AS $fn$
DECLARE n numeric;
BEGIN
    IF jsonb_typeof(v) <> 'number' THEN RETURN NULL; END IF;
    n := v::text::numeric;
    IF n < 0 OR n > 2147483647 OR n <> trunc(n) THEN RETURN NULL; END IF;
    RETURN n::integer;
END
$fn$;

CREATE OR REPLACE FUNCTION pg_temp.ls032_details(snap jsonb) RETURNS jsonb
LANGUAGE plpgsql IMMUTABLE STRICT AS $fn$
DECLARE
    fields text[] := ARRAY['Code','Name','Category','ProductSpecification','RawMaterialSpecification','Unit','Note'];
    details jsonb;
    warning integer := pg_temp.ls032_quantity(snap->'WarningQuantity');
BEGIN
    IF jsonb_typeof(snap->'IsActive') IS DISTINCT FROM 'boolean'
       OR (snap->'WarningQuantity' <> 'null'::jsonb AND warning IS NULL) THEN RETURN NULL; END IF;
    SELECT jsonb_object_agg(k, snap->k) INTO details
      FROM unnest(fields) AS f(k) WHERE jsonb_typeof(snap->k) = 'string';
    IF details IS NULL OR NOT (details ?& fields) THEN RETURN NULL; END IF;
    RETURN details || jsonb_build_object('IsActive', snap->'IsActive', 'WarningQuantity', warning);
END
$fn$;

DO $upgrade$
DECLARE
    runtime_role text := coalesce(nullif(current_setting('ls_inventory_upgrade.app_role'), ''), current_user);
    id_sequence text := pg_get_serial_sequence('product_histories','id');
    log_row record;
    doc jsonb; prv jsonb; nxt jsonb; old_details jsonb; new_details jsonb;
    balance integer; added integer; imported bigint := 0; examined bigint := 0;
BEGIN
    IF EXISTS (
        SELECT FROM (VALUES ('id','bigint',true),('product_id','uuid',true),('changed_at','timestamptz',true),
            ('user_name','text',true),('quantity','integer',true),('before_info','jsonb',false),('after_info','jsonb',true)
        ) AS expected(col, typ, required)
        LEFT JOIN pg_attribute a ON a.attrelid = 'product_histories'::regclass
            AND a.attname = expected.col AND NOT a.attisdropped
        WHERE a.atttypid IS DISTINCT FROM expected.typ::regtype OR a.attnotnull IS DISTINCT FROM expected.required
    ) THEN RAISE EXCEPTION '已有历史表的字段定义与 0.3.2 不符，已停止升级。'; END IF;
    IF id_sequence IS NULL OR NOT EXISTS (
        SELECT FROM pg_constraint fk
        WHERE fk.conrelid = 'product_histories'::regclass AND fk.contype = 'f'
          AND fk.confrelid = 'products'::regclass AND fk.confdeltype = 'r'
          AND fk.conkey = ARRAY[(SELECT attnum FROM pg_attribute WHERE attrelid = fk.conrelid AND attname = 'product_id')]
          AND fk.confkey = ARRAY[(SELECT attnum FROM pg_attribute WHERE attrelid = fk.confrelid AND attname = 'id')]
    ) THEN RAISE EXCEPTION '历史表的主键序列或商品外键与 0.3.2 不符，已停止升级。'; END IF;

    LOCK TABLE product_histories IN SHARE ROW EXCLUSIVE MODE;
    -- 空表可补录。已有记录时保留整条时间轴，避免重新导入已由新版写入的操作。
    IF EXISTS (SELECT FROM product_histories) THEN
        RAISE NOTICE '历史表已有记录，本次跳过整批补录。';
    ELSE
        FOR log_row IN SELECT id, occurred_at, user_name, action, detail FROM audit_logs
                       WHERE action IN ('新增商品','修改商品') ORDER BY id LOOP
            examined := examined + 1;
            BEGIN
                doc := log_row.detail::jsonb;
            EXCEPTION WHEN data_exception THEN CONTINUE;
            END;
            prv := NULL;
            nxt := doc;
            IF log_row.action = '修改商品' THEN
                prv := doc->'before';
                nxt := doc->'after';
            END IF;
            new_details := pg_temp.ls032_details(nxt);
            old_details := pg_temp.ls032_details(prv);
            balance := pg_temp.ls032_quantity(nxt->'Quantity');
            IF new_details IS NULL OR balance IS NULL OR nxt->>'Id' IS NULL
               OR (nxt->>'Id') !~* '^[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}$' THEN CONTINUE; END IF;
            IF log_row.action = '修改商品' AND (old_details IS NULL OR old_details = new_details
               OR lower(prv->>'Id') IS DISTINCT FROM lower(nxt->>'Id')) THEN CONTINUE; END IF;

            INSERT INTO product_histories (product_id, changed_at, user_name, quantity, before_info, after_info)
            SELECT p.id, log_row.occurred_at, log_row.user_name, balance, old_details, new_details
            FROM products p WHERE p.id = (nxt->>'Id')::uuid;
            GET DIAGNOSTICS added = ROW_COUNT;
            imported := imported + added;
        END LOOP;
        RAISE NOTICE '检查 % 条商品日志，补录 % 条，跳过 % 条。', examined, imported, examined-imported;
    END IF;

    IF runtime_role <> current_user THEN
        EXECUTE format('GRANT USAGE ON SCHEMA %I TO %I', current_schema(), runtime_role);
        EXECUTE format('GRANT SELECT, INSERT ON product_histories TO %I', runtime_role);
        EXECUTE format('REVOKE UPDATE, DELETE, TRUNCATE ON product_histories FROM %I', runtime_role);
        EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO %I', id_sequence, runtime_role);
    END IF;
    RAISE NOTICE '数据库 %，schema %，历史记录总数 %。', current_database(), current_schema(), (SELECT count(*) FROM product_histories);
END
$upgrade$;
COMMIT;
